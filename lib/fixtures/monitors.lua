-- See https://wiki.hypr.land/Configuring/Basics/Monitors/
-- List current monitors and supported resolutions with: hyprctl monitors all

local omarchy_gdk_scale = 1
local omarchy_monitor_scale = "auto"

hl.env("GDK_SCALE", tostring(omarchy_gdk_scale))

-- Primary panel: EDID advertises 100.00Hz as its highest rate.
-- desc: so the rule follows the panel if it moves to a different port.
hl.monitor({ output = "desc:HKC OVERSEAS LIMITED S01", mode = "1920x1080@100", position = "auto", scale = omarchy_monitor_scale })

-- Fallback for any monitor not matched above.
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = omarchy_monitor_scale })


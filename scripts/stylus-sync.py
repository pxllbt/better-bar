#!/usr/bin/env python3
"""
Sync Omarchy theme colors to a Stylus-accessible CSS variables file.

Reads colors.toml from the active Omarchy theme and writes a CSS file
with --theme-* custom properties. Stylus userstyles that use CSS variables
(e.g. ukishima) can @import this file to pick up the Omarchy palette:

    @import "file:///home/pixllbeat/.local/share/better/stylus-theme.css";
    :root {
        --background: var(--theme-background);
        --foreground: var(--theme-foreground);
    }

Note: In Chromium MV3, Stylus cannot @import from file:// URLs directly,
but the CSS can be loaded via a chrome-extension:// URL served by a
companion extension, or the user can copy the variables into their
userstyle's @var block. The file is also useful as a reference for
manually syncing Stylus @var values when the theme changes.

Usage:
    stylus-sync.py [colors.toml_path] [output_css_path]

Defaults:
    colors.toml: ~/.local/state/omarchy/current/theme/colors.toml
    output:      ~/.local/share/better/stylus-theme.css
"""

import os
import re
import sys

DEFAULT_COLORS_PATH = os.path.expanduser(
    "~/.local/state/omarchy/current/theme/colors.toml"
)
DEFAULT_OUTPUT_PATH = os.path.expanduser(
    "~/.local/share/better/stylus-theme.css"
)

# Maps colors.toml keys to CSS custom property names.
# These are the standard tokens that Stylus userstyles commonly reference.
COLOR_MAP = {
    "background": "--theme-background",
    "dark_background": "--theme-dark-background",
    "darker_background": "--theme-darker-background",
    "lighter_background": "--theme-lighter-background",
    "foreground": "--theme-foreground",
    "dark_foreground": "--theme-dark-foreground",
    "light_foreground": "--theme-light-foreground",
    "bright_foreground": "--theme-bright-foreground",
    "accent": "--theme-accent",
    "muted": "--theme-muted",
    "selection": "--theme-selection",
    "selection_background": "--theme-selection-background",
    "selection_foreground": "--theme-selection-foreground",
    "red": "--theme-red",
    "yellow": "--theme-yellow",
    "orange": "--theme-orange",
    "green": "--theme-green",
    "cyan": "--theme-cyan",
    "blue": "--theme-blue",
    "magenta": "--theme-magenta",
    "brown": "--theme-brown",
    "bright_red": "--theme-bright-red",
    "bright_yellow": "--theme-bright-yellow",
    "bright_green": "--theme-bright-green",
    "bright_cyan": "--theme-bright-cyan",
    "bright_blue": "--theme-bright-blue",
    "bright_magenta": "--theme-bright-magenta",
}


def parse_colors_toml(path):
    """Parse colors.toml and return a dict of key -> color string."""
    colors = {}
    if not os.path.exists(path):
        return colors
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            # Match: key = "#hex" or key = "value"
            m = re.match(r'^([A-Za-z0-9_-]+)\s*=\s*"(.+)"', line)
            if m:
                key = m.group(1)
                val = m.group(2)
                # Only keep color values (hex or rgba)
                if val.startswith("#") or val.startswith("rgba"):
                    colors[key] = val
    return colors


def generate_css(colors):
    """Generate CSS with --theme-* custom properties from colors dict."""
    lines = []
    lines.append("/*")
    lines.append(" * Auto-generated by pix.bar stylus-sync.py")
    lines.append(" * Do not edit manually; regenerates on theme change.")
    lines.append(" * Syncs Omarchy theme colors for Stylus userstyles.")
    lines.append(" */")
    lines.append(":root {")
    for key, css_var in COLOR_MAP.items():
        if key in colors:
            lines.append(f"  {css_var}: {colors[key]};")
    # Always include mode
    mode = colors.get("mode", "dark")
    lines.append(f"  --theme-mode: {mode};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    colors_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_COLORS_PATH
    output_path = (
        sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUTPUT_PATH
    )

    colors = parse_colors_toml(colors_path)
    if not colors:
        print(f"warning: no colors found at {colors_path}", file=sys.stderr)

    css = generate_css(colors)

    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        f.write(css)

    print(f"wrote {len(COLOR_MAP)} color variables to {output_path}")


if __name__ == "__main__":
    main()
